import re
from pathlib import Path

def extract_summary_blocks(text: str) -> list[str]:
    # 1) ANSI color code ???? (??: \x1b[92m ...)
    text = re.sub(r"\x1b\[[0-9;]*m", "", text)

    # 2) summary ????(= ???? ???????? ???? = ???? ?????? ??????)?? ????
    #    "================================================================================" ???? ???? ???? 80?? ?????????? {80,}?? ????
    block_re = re.compile(r"(={80,}\n.*?={80,}\n)", re.S)

    blocks = []
    for b in block_re.findall(text):
        # summary???? ???????? ???????? ??????(?????? ???? ?? ???? ????)
        if "Target Label" in b and "Files Processed" in b:
            blocks.append(b.strip())
    return blocks

def main(infile: str, outfile: str = "summary_only.txt"):
    txt = Path(infile).read_text(errors="replace")
    blocks = extract_summary_blocks(txt)

    out = "\n\n".join(blocks) + ("\n" if blocks else "")
    Path(outfile).write_text(out)
    print(f"[DONE] extracted {len(blocks)} block(s) -> {outfile}")

if __name__ == "__main__":
    main("genWeightReport.txt", "summary_only.txt")
